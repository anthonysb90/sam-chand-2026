// Turns the attendee list (CSV) into one-way hashes the resources page can check
// without exposing anyone's name, email, or phone number.
//
// Usage: node tools/build-attendees.js path/to/attendees.csv
// The CSV needs a header row with columns containing "email" and "phone".
// Never commit the CSV itself. Only assets/attendees.js is committed.

const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const ITERATIONS = 150000;

function parseCsv(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field); rows.push(row); row = []; field = "";
    } else field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows.filter(r => r.some(v => v.trim()));
}

const normEmail = s => s.trim().toLowerCase();
const normPhone = s => {
  const d = s.replace(/\D/g, "");
  return d.length >= 10 ? d.slice(-10) : "";
};
const hash = (value, salt) =>
  crypto.pbkdf2Sync(value, salt, ITERATIONS, 32, "sha256").toString("hex");

const file = process.argv[2];
if (!file) { console.error("Usage: node tools/build-attendees.js attendees.csv"); process.exit(1); }

const [header, ...rows] = parseCsv(fs.readFileSync(file, "utf8").replace(/^﻿/, ""));
const col = word => header.findIndex(h => h.toLowerCase().includes(word));
const emailCol = col("email"), phoneCol = col("phone");
if (emailCol < 0 && phoneCol < 0) { console.error("No email or phone column found in header:", header); process.exit(1); }

const salt = crypto.randomBytes(16).toString("hex");
const emails = new Set(), phones = new Set();
for (const r of rows) {
  const e = emailCol >= 0 ? normEmail(r[emailCol] || "") : "";
  const p = phoneCol >= 0 ? normPhone(r[phoneCol] || "") : "";
  if (e.includes("@")) emails.add(hash("e:" + e, salt));
  if (p) phones.add(hash("p:" + p, salt));
}

const out = `// Generated by tools/build-attendees.js. Do not edit by hand.
// One-way hashes only. No names, emails, or phone numbers are stored here.
window.ATTENDEES = ${JSON.stringify({
  salt, iterations: ITERATIONS,
  emails: [...emails].sort(), phones: [...phones].sort()
})};
`;
fs.writeFileSync(path.join(__dirname, "..", "assets", "attendees.js"), out);
console.log(`Rows: ${rows.length} | email hashes: ${emails.size} | phone hashes: ${phones.size}`);
